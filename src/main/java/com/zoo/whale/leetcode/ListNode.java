package com.zoo.whale.leetcode;

/**
 * Definition for singly-linked list.
 * @Date: 2024年 11月 28日
 * @Time:16时:28分
 * @Author: weixin.liu
 * @Version:V1.0
 */
public class ListNode {

    int val;
    ListNode next;

    ListNode() {
    }

    ListNode(int val) {
        this.val = val;
    }

    ListNode(int val, ListNode next) {
        this.val = val;
        this.next = next;
    }

}
